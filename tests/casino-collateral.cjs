'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const exactWallet=require('../exact-wallet');
const {createJBank}=require('../j-bank-core');
const {createCasinoCollateral}=require('../casino-collateral');
const db0=new DatabaseSync(':memory:');
db0.exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,rank_level INTEGER NOT NULL DEFAULT 0,is_disabled INTEGER NOT NULL DEFAULT 0,balance INTEGER NOT NULL,balance_exact TEXT,balance_base TEXT);
CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT NOT NULL,updated_at INTEGER NOT NULL);
CREATE TABLE ledger(id INTEGER PRIMARY KEY AUTOINCREMENT,user_id INTEGER,amount INTEGER,balance_after INTEGER,amount_exact TEXT,balance_after_exact TEXT,type TEXT,memo TEXT,created_at INTEGER);
CREATE TABLE room_escrow(room_id TEXT NOT NULL,user_id INTEGER NOT NULL,amount INTEGER NOT NULL,amount_exact TEXT,game TEXT NOT NULL,created_at INTEGER NOT NULL,PRIMARY KEY(room_id,user_id));`);
const db={exec:s=>db0.exec(s),prepare:s=>{const q=db0.prepare(s);q.setReadBigInts(true);return q;}};
const T=1000000000000n,levels=[{level:0,name:'평민',cost:0},{level:1,name:'자작',cost:String(T)},{level:2,name:'백작',cost:String(T*5n)},{level:3,name:'공작',cost:String(T*10n)}];
const now=()=>1793512800000,kstDate=()=> '2026-11-01';
const bank=createJBank({db,exactWallet,levels,now,kstDate});
const collateral=createCasinoCollateral({db,exactWallet,jBank:bank,levels,now});
const add=(id,rank,money)=>db.prepare('INSERT INTO users(id,rank_level,balance,balance_exact,balance_base) VALUES(?,?,?,?,?)').run(id,rank,exactWallet.mirror(money),String(money),String(exactWallet.mirror(money)));
const wallet=id=>exactWallet.read(db.prepare('SELECT balance,balance_exact,balance_base FROM users WHERE id=?').get(id));
const tier=id=>Number(db.prepare('SELECT rank_level FROM users WHERE id=?').get(id).rank_level);
const transact=fn=>{db.exec('BEGIN IMMEDIATE');try{const v=fn();db.exec('COMMIT');return v;}catch(e){try{db.exec('ROLLBACK')}catch{}throw e;}};
add(1,3,T);add(2,0,20n*T);
assert.equal(collateral.available(1).total, T+(T+5n*T+10n*T)*99n/100n);
const room='COLLATERAL_CASE_1';
transact(()=>{collateral.reserve(room,1,16n*T,'hula');collateral.reserve(room,2,16n*T,'hula');});
assert.equal(wallet(1),0n,'cash was escrowed');
assert.equal(wallet(2),4n*T);
assert.throws(()=>transact(()=>collateral.reserve('DOUBLE_PLEDGE',1,T,'hula')),/다른 카지노/);
assert.throws(()=>bank.borrow(1,'1000000','casino_pledge_locks_loan_0001'),/담보/);
const result=transact(()=>({loser:collateral.settle(room,1,4n*T),winner:collateral.settle(room,2,0n,4n*T)}));
assert.equal(result.loser.net,String(-4n*T));
assert.equal(result.winner.net,String(4n*T));
assert.equal(tier(1),2,'exactly one rank tier sold');
assert.equal(wallet(1),T*69n/10n,'9.9T sale minus 3T loss after 1T escrow');
assert.equal(wallet(2),24n*T,'winner collects exactly the 4T loser lost');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM room_escrow').get().n,0n);
assert.throws(()=>transact(()=>collateral.settle(room,1,0n)),/보증 기록/,'repeat settlement cannot mint G');
const escrowRevenue=BigInt(db.prepare("SELECT COALESCE(SUM(amount),0) AS amount FROM ledger WHERE user_id=1 AND type='casino_rank_sale'").get().amount);
assert.equal(escrowRevenue,99n*T/10n,'99 percent rank sale');
const noSale='COLLATERAL_NO_SALE';
transact(()=>collateral.reserve(noSale,2,16n*T,'hula'));
transact(()=>collateral.settle(noSale,2,0n));
assert.equal(wallet(2),24n*T,'draw or cancel refunds full escrow');
assert.equal(tier(2),0);
add(3,3,T);
db.prepare('INSERT INTO game_state(key,value,updated_at) VALUES(?,?,?)').run('jbank:account:3',JSON.stringify({principal:String(2n*T),interest:'0',asOf:kstDate()}),now());
assert.equal(bank.owed(3),2n*T);
transact(()=>collateral.reserve('BANK_PRIORITY',3,14n*T,'hula'));
transact(()=>collateral.settle('BANK_PRIORITY',3,4n*T));
assert.equal(bank.owed(3),0n,'bank debt repaid before casino losses');
assert.equal(tier(3),2);
assert.equal(wallet(3),T*49n/10n,'9.9T rank sale minus 2T bank debt minus 3T casino shortfall');
add(4,0,T);
assert.throws(()=>transact(()=>collateral.reserve('INSUFFICIENT',4,16n*T,'hula')),/담보|부족/);
assert.equal(wallet(4),T);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM room_escrow').get().n,0n);
add(5,0,0n);
db.prepare('INSERT INTO room_escrow(room_id,user_id,amount,amount_exact,game,created_at) VALUES(?,?,?,?,?,?)').run('LOBBY',5,T,String(T),'gostop',now());
transact(()=>collateral.reserve('LOBBY',5,1n*T,'matgo_multi',{existing:true}));
assert.equal(wallet(5),0n,'lobby money had already been deducted by caller');
transact(()=>collateral.settle('LOBBY',5,T));
assert.equal(wallet(5),0n,'lobby cash escrow is entirely lost without a double debit');
console.log('CASINO_COLLATERAL_OK: exact G, 16x coverage, 99% forced tier sale, bank-first debt, zero-sum multiplayer, replay safety, refund, pledge lock, lobby conversion');
