const add=(id,money,level=11)=>{
 const mirror=exactWallet.mirror(money);
 db.prepare('INSERT INTO users(id,balance,balance_exact,balance_base,rank_level) VALUES(?,?,?,?,?)').run(id,mirror,String(money),String(mirror),level);
};
const profile=id=>db.prepare('SELECT balance,balance_exact,balance_base,rank_level FROM users WHERE id=?').get(id);
