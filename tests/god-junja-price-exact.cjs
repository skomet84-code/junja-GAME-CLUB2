assert.equal(profile(2).rank_level,11n,'failed purchase never promotes');
assert.equal(exactWallet.read(profile(2)),cost-1n,'failed purchase retains full balance');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ledger WHERE user_id=2').get().n,0n,'no charge on failure');
const huge=123456789012345678900000n;
add(3,huge);
const bigResult=ctx.promoteSocialRank(3);
assert.equal(bigResult.rank.level,12);
assert.equal(bigResult.balance,String(huge-cost));
assert.equal(exactWallet.read(profile(3)),huge-cost,'far beyond int64 exact funds remain intact');
assert.equal(db.prepare('SELECT balance_after_exact FROM ledger WHERE user_id=3').get().balance_after_exact,String(huge-cost));
const transcended=ctx.promoteSocialRank(3);
assert.equal(transcended.rank.level,13,'THE ABSOLUTE can ascend to GOD JUNJA');
assert.equal(exactWallet.read(profile(3)),huge-cost-1000000000000000000n,'100경 deduction exact at massive balances');
assert.equal(db.prepare('SELECT amount_exact FROM ledger WHERE user_id=3 ORDER BY rowid DESC LIMIT 1').get().amount_exact,'-1000000000000000000');
