const fmtEnd=ui.indexOf('\nlet state=null;',fmtStart);
assert.ok(fmtStart>=0&&fmtEnd>fmtStart,'extract exact UI formatter');
const fmt=vm.runInNewContext(ui.slice(fmtStart,fmtEnd)+'\nfmt;');
