'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {DatabaseSync}=require('node:sqlite');
const exactWallet=require('../exact-wallet');
const source=fs.readFileSync(path.join(__dirname,'..','server.js'),'utf8');
const ui=fs.readFileSync(path.join(__dirname,'..','public','rank-system.js'),'utf8');
const rankStart=source.indexOf('const SOCIAL_RANKS = [');
const rankEnd=source.indexOf('\n];',rankStart)+3;
