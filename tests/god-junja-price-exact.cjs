add(5,1000000000000000000n,12);
assert.equal(ctx.promoteSocialRank(5).rank.level,13,'exact 100경 allows GOD JUNJA ascension');
assert.equal(exactWallet.read(profile(5)),0n,'exact 100경 deducted');
