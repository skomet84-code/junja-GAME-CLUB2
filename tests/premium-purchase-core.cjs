'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {createPremiumPurchaseCore,PRODUCTS}=require('../premium-purchase-core');
(async()=>{
 const folder=fs.mkdtempSync(path.join(os.tmpdir(),'junja-premium-'));
 const file=path.join(folder,'db.sqlite');
 let db=new DatabaseSync(file);db.exec('PRAGMA foreign_keys=ON; CREATE TABLE users (id INTEGER PRIMARY KEY,is_disabled INTEGER NOT NULL DEFAULT 0,balance INTEGER NOT NULL); CREATE TABLE ledger(id INTEGER PRIMARY KEY,user_id INTEGER,amount INTEGER); INSERT INTO users(id,balance) VALUES(1,777777),(2,555555);');
 const badCode=(code)=>e=>e&&e.code===code;
 let paymentStatus='APPROVED', refundStatus='REFUNDED', paymentAmountAdjust=0, paymentOrderOverride=null;
 const verifyPayment=async p=>({status:paymentStatus,orderId:paymentOrderOverride||p.orderId,paymentKey:p.paymentKey,amountKrw:p.expectedAmountKrw+paymentAmountAdjust,currency:'KRW'});
 const verifyRefund=async p=>({status:refundStatus,orderId:p.orderId,paymentKey:p.paymentKey,amountKrw:p.expectedAmountKrw,currency:'KRW'});
 const locked=createPremiumPurchaseCore({db,verifyPayment,verifyRefund});
 assert.throws(()=>locked.createOrder({userId:1,productId:PRODUCTS[0].id,requestId:'request-aaaaaaaa'}),badCode('PAYMENTS_DISABLED'));
 assert.equal(locked.getOwned(1).length,0);
 const service=createPremiumPurchaseCore({db,enabled:true,verifyPayment,verifyRefund,now:()=>1770000000000});
 assert.equal(service.getCatalog().length,6);
 assert(service.getCatalog().every(p=>p.transferable===false&&p.gameplayBenefit===false));
 const a=service.createOrder({userId:1,productId:'imperial_watch_room',requestId:'request-aaaaaaaa'});
 assert.equal(a.amountKrw,9900);assert.equal(a.status,'PENDING');
 assert.deepEqual(service.createOrder({userId:1,productId:'imperial_watch_room',requestId:'request-aaaaaaaa'}),a);
 assert.deepEqual(service.createOrder({userId:1,productId:'imperial_watch_room',requestId:'request-bbbbbbbb'}),a);
 assert.throws(()=>service.createOrder({userId:1,productId:'royal_motor_lounge',requestId:'request-aaaaaaaa'}),badCode('REQUEST_CONFLICT'));
 paymentAmountAdjust=1;
 await assert.rejects(service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-aa00001'}),badCode('PROVIDER_MISMATCH'));
 assert.equal(service.getOwned(1).length,0);
 paymentAmountAdjust=0;paymentOrderOverride='fake-order-id';
 await assert.rejects(service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-aa00001'}),badCode('PROVIDER_MISMATCH'));
 paymentOrderOverride=null;paymentStatus='FAILED';
 await assert.rejects(service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-aa00001'}),badCode('PROVIDER_MISMATCH'));
 paymentStatus='APPROVED';
 const first=await service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-aa00001'});
 assert.equal(first.alreadyApplied,false);assert.equal(first.order.status,'PAID');
 const second=await service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-aa00001'});
 assert.equal(second.alreadyApplied,true);
 await assert.rejects(service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-bad-key'}),badCode('PAYMENT_CONFLICT'));
 assert.equal(service.getOwned(1).length,1);
 assert.equal(service.getOwned(2).length,0);
 assert.throws(()=>service.createOrder({userId:1,productId:'imperial_watch_room',requestId:'request-cccccccc'}),badCode('ALREADY_OWNED'));
 const b=service.createOrder({userId:2,productId:'imperial_watch_room',requestId:'request-dddddddd'});
 await assert.rejects(service.fulfillApprovedOrder({orderId:b.orderId,paymentKey:'provider-aa00001'}));
 assert.equal(service.getOwned(2).length,0);
 const finalB=await service.fulfillApprovedOrder({orderId:b.orderId,paymentKey:'provider-bb00002'});
 assert.equal(finalB.order.status,'PAID');
 refundStatus='FAILED';
 await assert.rejects(service.applyVerifiedRefund({orderId:a.orderId}),badCode('PROVIDER_MISMATCH'));
 assert.equal(service.getOwned(1).length,1);
 refundStatus='REFUNDED';
 const ref=await service.applyVerifiedRefund({orderId:a.orderId});assert.equal(ref.order.status,'REFUNDED');
 assert.equal(service.getOwned(1).length,0);
 assert.equal((await service.applyVerifiedRefund({orderId:a.orderId})).alreadyApplied,true);
 await assert.rejects(service.fulfillApprovedOrder({orderId:a.orderId,paymentKey:'provider-aa00001'}),badCode('ORDER_REFUNDED'));
 const repurchase=service.createOrder({userId:1,productId:'imperial_watch_room',requestId:'request-eeeeeeee'});
 await service.fulfillApprovedOrder({orderId:repurchase.orderId,paymentKey:'provider-cc00003'});
 assert.equal(service.getOwned(1).length,1);
 await service.applyVerifiedRefund({orderId:a.orderId});assert.equal(service.getOwned(1).length,1);
 db.exec('UPDATE users SET is_disabled=1 WHERE id=2');
 assert.throws(()=>service.createOrder({userId:2,productId:'marina_suite',requestId:'request-ffffffff'}),badCode('USER_UNAVAILABLE'));
 assert.equal(db.prepare('SELECT balance FROM users WHERE id=1').get().balance,777777);
 assert.equal(db.prepare('SELECT balance FROM users WHERE id=2').get().balance,555555);
 assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ledger').get().n,0);
 const countBefore=service.getOwned(1).length;db.close();db=new DatabaseSync(file);
 const restarted=createPremiumPurchaseCore({db});
 assert.equal(restarted.getOwned(1).length,countBefore,'Entitlement survives SQLite reopen');
 assert.equal(restarted.getOrders(1).filter(x=>x.status==='PAID').length,1);
 db.close();fs.rmSync(folder,{recursive:true,force:true});
 console.log('PREMIUM_CORE_OK: disabled default, trusted PG verification, idempotency, replay defense, refunds, persistence, G-wallet isolation');
})().catch(e=>{console.error(e);process.exitCode=1});
