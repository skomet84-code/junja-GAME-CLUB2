'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createSupportCenter}=require('../support-center-core');
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT,updated_at INTEGER);CREATE TABLE users(id INTEGER PRIMARY KEY,nickname TEXT,balance INTEGER);CREATE TABLE ledger(id INTEGER PRIMARY KEY,user_id INTEGER,amount INTEGER);INSERT INTO users VALUES(1,'준자',1000000),(2,'햅피',2000000);INSERT INTO ledger VALUES(1,1,-100),(2,2,200);");
let now=Date.UTC(2026,10,5),core=createSupportCenter({db,now:()=>now});
function req(id,requestId,subject='정산 결과 다시 봐주세요',message='룰렛 123회 지급금액 다시 확인이 필요합니다.'){
 return {userId:id,category:'game_settlement',subject,message,requestId};
}
const original=db.prepare('SELECT SUM(balance) AS total FROM users').get().total;
const a=core.create(req(1,'request_user1_00000001'));
assert.equal(a.reference,'JCS-00000001');
assert.equal(a.status,'OPEN');
assert.equal(a.version,1);
assert.equal(a.duplicate,false);
assert.equal(core.create(req(1,'request_user1_00000001')).duplicate,true);
assert.throws(()=>core.create(req(1,'request_user1_00000001','다른 문의 제목입니다')),/같은 요청번호/);
assert.equal(core.userList(1).items.length,1);
assert.equal(core.userList(2).items.length,0);
assert.throws(()=>core.create(req(1,'request_user1_00000002','abc','길이가 충분합니다.')),/더 작성/);
assert.throws(()=>core.create({...req(1,'request_user1_00000003'),category:'credit_card'}),/문의 종류/);
const b=core.create(req(1,'request_user1_00000004','코인 투자 확인 요청','코인 전산기록 확인이 필요합니다.'));
const c=core.create(req(1,'request_user1_00000005','명품관 체험 문의','프리미엄 체험에 관한 문의입니다.'));
assert.equal(core.userList(1).items.length,3);
assert.throws(()=>core.create(req(1,'request_user1_00000006','추가 정산 확인 요청','추가 기록 확인 요청입니다.')),/3건/);
const other=core.create({userId:2,category:'refund_inquiry',subject:'환불 가능 여부 확인',message:'현재 현금 결제가 아직 비활성화인 걸 알고 문의합니다.',requestId:'request_user2_00000001'});
assert.equal(other.id,4);
assert.equal(other.status,'OPEN');
assert.equal(core.userList(2).items.length,1);
assert.equal(core.adminList().items.length,4);
assert.equal(core.adminList({status:'OPEN'}).items.length,4);
assert.equal(core.adminList().items[0].nickname,'햅피');
assert.equal(core.adminList().items[0].message,other.message);
assert.throws(()=>core.adminList({status:'WRONG'}),/상태 필터/);
const update={operatorId:1,id:a.id,status:'REVIEWING',adminNote:'원장과 영수증을 대조하고 있습니다.',expectedVersion:1,requestId:'owner_support_00000001'};
const review=core.update(update);
assert.equal(review.status,'REVIEWING');
assert.equal(review.version,2);
assert.equal(core.update(update).duplicate,true);
assert.throws(()=>core.update({...update,requestId:'owner_support_00000002'}),/다시 조회/);
assert.throws(()=>core.update({...update,id:other.id,requestId:'owner_support_00000003',status:'OPEN'}),/상태 변경/);
const done=core.update({operatorId:1,id:a.id,status:'RESOLVED',adminNote:'실결제와 관련 없는 게임 정산 안내 완료',expectedVersion:2,requestId:'owner_support_00000004'});
assert.equal(done.status,'RESOLVED');
assert.equal(core.adminList({status:'RESOLVED'}).items.length,1);
assert.equal(core.userList(1).items[2].adminNote,'실결제와 관련 없는 게임 정산 안내 완료');
const reopenCap=core.create(req(1,'request_user1_00000006','추가 정산 확인 요청','추가 기록 확인 요청입니다.'));
assert.equal(reopenCap.id,5,'Resolved cases should not count as open.');
const closed=core.update({operatorId:1,id:other.id,status:'CLOSED',adminNote:'실결제 미오픈으로 환불 대상 결제 없음',expectedVersion:1,requestId:'owner_support_00000005'});
assert.equal(closed.status,'CLOSED');
assert.throws(()=>core.update({operatorId:1,id:other.id,status:'REVIEWING',adminNote:'',expectedVersion:2,requestId:'owner_support_00000006'}),/종결/);
// Read fresh state after constructing a new instance (simulated restart).
now+=86400000;core=createSupportCenter({db,now:()=>now});
assert.equal(core.userList(1).items[0].id,5);
assert.equal(core.userList(2).items[0].status,'CLOSED');
assert.equal(core.adminList({status:'CLOSED'}).items.length,1);
assert.equal(db.prepare('SELECT SUM(balance) AS total FROM users').get().total,original);
