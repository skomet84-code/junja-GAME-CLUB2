'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const app=fs.readFileSync('public/app.js','utf8');
const html=fs.readFileSync('public/index.html','utf8');
const css=fs.readFileSync('public/yut-toss-real-v3.css','utf8');
const a=app.indexOf('function yutSticksHtml('),b=app.indexOf("let yutSeenAction='';",a);
assert.ok(a>0&&b>a,'isolated yut render helper');
const context={};
vm.createContext(context);vm.runInContext(app.slice(a,b)+'\nthis.sticks=yutSticksHtml;',context);
const render=context.sticks;
const first=render([0,1,1,1],false);
const second=render([1,1,1,1],false);
assert.equal((first.match(/class="yut-stick back-face/g)||[]).length,1,'one back face');
assert.equal((first.match(/class="yut-stick flat-face/g)||[]).length,3,'three flat faces');
assert.equal((second.match(/class="yut-stick flat-face/g)||[]).length,4);
assert.match(render([1,0,0,0],false),/걸 · 3칸 앞으로/,'three patterned backs are GEOL, not BACK DO');
assert.match(render([0,1,1,1],false),/빽도 · 1칸 뒤로/,'marked first back alone is BACK DO');
assert.match(render([1,0,1,1],false),/도 · 1칸 앞으로/,'unmarked single back is DO');
assert.match(render([0,0,1,1],false),/개 · 2칸 앞으로/);
assert.match(render([0,0,0,0],false),/윷 · 4칸 앞으로/);
assert.match(render([1,1,1,1],false),/모 · 5칸 앞으로/);
assert.match(render(null,false),/윷가락을 던지면 결과가 표시돼/,'no fabricated faces before throw');
assert.doesNotMatch(render(null,false),/class="yut-stick /,'no fake sticks while waiting');
assert.equal((first.match(/class="yut-stick-body"/g)||[]).length,4,'four 3-D bodies');
assert.equal((first.match(/class="yut-stick-face yut-face-flat"/g)||[]).length,4,'four fronts');
assert.equal((first.match(/class="yut-stick-face yut-face-back"/g)||[]).length,4,'four backs');
assert.equal((first.match(/--rest-face:180deg/g)||[]).length,1,'server backs are rendered as backs');
assert.equal((first.match(/--rest-face:0deg/g)||[]).length,3,'server flats are rendered as flats');
assert.equal((first.match(/class="yut-backdo-dot"/g)||[]).length,1,'only marked stick has back-do marker');
assert.ok(render([1,1,1,1],true).includes('yut-real-toss throwing'),'single finite toss animation');
assert.ok(css.includes('@keyframes yutRealArc')&&css.includes('@keyframes yutRealFlip')&&css.includes('@keyframes yutRealShadow'));
assert.match(css,/calc\(720deg \+ var\(--rest-face\)\)/,'full flips land on authoritative side');
assert.match(css,/prefers-reduced-motion:reduce/);
assert.match(css,/1\.34s linear both!important/,'no infinite toss animation');
assert.ok(!/animation:[^;\n]*infinite/.test(css),'scene animations are finite, unlike legacy wiggle');
assert.ok(html.includes('yut-toss-real-v3.css?v='),'last-loaded winning CSS');
assert.ok(app.includes('async function playYutServerToss(root,sticks,ms)'),'one shared server-controlled toss helper');
assert.ok(app.includes('scene.outerHTML=yutSticksHtml(sticks,true)'),'toss animates four authoritative faces, not stale ones');
assert.ok(app.includes('await playYutServerToss(root,d.game?.last?.sticks,1610);renderSoloYut(d.game)'),'solo throw animates confirmed roll before final render');
assert.ok(app.includes('await playYutServerToss(root,d.room?.yut?.last?.sticks,1750);renderYut(d.room)'),'multiplayer throw animates confirmed roll before final render');
assert.ok(!app.includes("btn.disabled=true;$('.yut-toss-scene',root)?.classList.add('throwing')"),'no stale multiplayer faces spinning');
const cases=[['빽도',[0,1,1,1],1],['도',[1,0,1,1],1],['개',[0,0,1,1],2],['걸',[0,0,0,1],3],['윷',[0,0,0,0],4],['모',[1,1,1,1],0]];
for(const [name,sticks,backCount] of cases){
 const markup=render(sticks,true);
 assert.equal((markup.match(/class="yut-stick back-face/g)||[]).length,backCount,name+' landing face count');
 assert.equal((markup.match(/class="yut-stick flat-face/g)||[]).length,4-backCount,name+' opposite faces');
}

assert.ok(app.includes("await sleep(1530);nextScene?.classList.remove('throwing')"),'AI replay lasts until last stick lands');
console.log('YUT_REAL_TOSS_OK: 3-D faces, synchronized arcs/flip/impact, finite motion, authoritative outcomes, mobile and reduced-motion');
