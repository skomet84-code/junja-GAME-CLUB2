'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const exactWallet=require('../exact-wallet');
const {STAKES,stakeValue,createOmokAiWager}=require('../omok-ai-wager');
const sqlite=new DatabaseSync(':memory:');
sqlite.exec(`CREATE TABLE users(id INTEGER PRIMARY KEY,is_disabled INTEGER DEFAULT 0,balance INTEGER,balance_exact TEXT,balance_base TEXT);
 CREATE TABLE ledger(id INTEGER PRIMARY KEY AUTOINCREMENT,user_id INTEGER,amount INTEGER,balance_after INTEGER,amount_exact TEXT,balance_after_exact TEXT,type TEXT,memo TEXT,created_at INTEGER);
 CREATE TABLE room_escrow(room_id TEXT,user_id INTEGER,amount INTEGER,amount_exact TEXT,game TEXT,created_at INTEGER,PRIMARY KEY(room_id,user_id));
 CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT,updated_at INTEGER);`);
const db={exec:s=>sqlite.exec(s),prepare:s=>{const q=sqlite.prepare(s);q.setReadBigInts(true);return q;}};
const initial=5000000000000000n;
db.prepare('INSERT INTO users(id,balance,balance_exact,balance_base) VALUES(?,?,?,?)').run(9,exactWallet.mirror(initial),String(initial),String(exactWallet.mirror(initial)));
const balance=()=>exactWallet.read(db.prepare('SELECT balance,balance_exact,balance_base FROM users WHERE id=?').get(9));
const wager=createOmokAiWager({db,exactWallet,now:()=>1700000000000});
const make=(id,stake='1000000')=>({id,aiMode:true,stake,round:1,players:[{id:9},{id:0}],escrowed:false});
assert.ok(STAKES.includes('1000000000000'));
assert.throws(()=>stakeValue('9999'),/판돈/);
const win=make('OM_WIN');
wager.reserve(win);
assert.equal(balance(),initial-1000000n);
assert.equal(db.prepare('SELECT COUNT(*) c FROM room_escrow').get().c,1n);
assert.deepEqual(wager.settle(win,9),{stake:'1000000',net:1000000,outcome:'win'});
assert.equal(balance(),initial+1000000n);
assert.throws(()=>wager.settle(win,9),/예치/,'duplicate credit refused');
const draw=make('OM_DRAW');
const beforeDraw=balance();wager.reserve(draw);
assert.equal(wager.settle(draw,null).outcome,'draw');
assert.equal(balance(),beforeDraw,'draw returns full stake');
const lose=make('OM_LOSS','1000000000000');
const beforeLoss=balance();wager.reserve(lose);
assert.equal(wager.settle(lose,0).outcome,'loss');
assert.equal(balance(),beforeLoss-1000000000000n,'AI win costs one stake');
assert.equal(db.prepare('SELECT COUNT(*) c FROM room_escrow').get().c,0n);
const poor=make('OM_POOR','1000000000000');
db.prepare('UPDATE users SET balance=?,balance_exact=?,balance_base=? WHERE id=9').run(50n,'50','50');
assert.throws(()=>wager.reserve(poor),/부족/);
assert.equal(balance(),50n);
assert.equal(db.prepare('SELECT COUNT(*) c FROM room_escrow').get().c,0n);
console.log('OMOK_AI_WAGER_OK: win, loss, refund, insufficient stake, exact-balance and replay safety');
