'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..'),src=p=>fs.readFileSync(path.join(root,p),'utf8');
const manifest=JSON.parse(src('docs/COMMERCE_GO_LIVE_GATE.json'));
const server=src('server.js'),ui=src('public/commerce-readiness-ui.js'),html=src('public/index.html'),css=src('public/commerce-readiness.css'),core=src('commerce-readiness-v10.js'),preview=src('public/premium-preview.html');
assert.equal(manifest.goLive,false,'Do not activate commerce without approvals');
assert.equal(manifest.required.length,12);
assert.equal(manifest.required.filter(x=>x.status==='blocked').length,10);
assert.equal(manifest.required.filter(x=>x.status==='prototype-tested').length,2);
assert.match(core,/livePaymentsEnabled:false/);
assert.match(core,/productionCheckoutAvailable:false/);
assert.match(core,/checkoutBlocked:true/);
assert.doesNotMatch(core,/\.run\(|\.exec\(|POST|TossPayments|fetch\(|cancelPayment|confirmPayment|update\s+users/i,'Readiness gate must never process payments or modify game wallets');
assert(server.includes("url.pathname==='/api/admin/commerce-readiness'&&req.method==='GET'"));
assert(server.includes("if(!owner.jpl_access)return json(res,403"));
assert(!/url\.pathname\s*===\s*['"]\/api\/premium\/checkout['"]/.test(server),'No live checkout route should be wired');
assert(!/url\.pathname\s*===\s*['"]\/api\/premium\/confirm['"]/.test(server),'No real payment approval endpoint');
assert.equal((preview.match(/<button disabled type="button">판매 준비 중<\/button>/g)||[]).length,6,'All six cosmetic purchase controls must remain disabled');
assert(!preview.includes('<script'),'Preview must never initiate a checkout');
assert(html.includes('id="commerceReadinessPanel"'));
assert(html.includes('id="commerceReadinessRefresh"'));
assert(html.includes('id="commerceReadinessItems"'));
assert(html.includes('/commerce-readiness-ui.js?v='));
assert(html.includes('/commerce-readiness.css?v='));
assert.match(css,/@media\(max-width:650px\)/);
assert(ui.includes("fetch('/api/admin/commerce-readiness"));
assert(!/innerHTML\s*=/.test(ui),'Commercial evidence must render as safe DOM text');
assert(!/method:\s*'POST'|\/api\/premium\/buy|TossPayments/.test(ui));
console.log('COMMERCE_V10_STATIC_OFF_OK: 12 requirements, six purchases disabled, owner-only GET, no live checkout, no money movement');
