'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const {DatabaseSync}=require('node:sqlite'),exactWallet=require('../exact-wallet');
const {createJStocks,STOCKS,MARKET_KEY,sessionHour}=require('../j-stock-core');
const sql=new DatabaseSync(':memory:');
sql.exec("CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT,updated_at INTEGER);CREATE TABLE users(id INTEGER PRIMARY KEY,nickname TEXT,is_disabled INTEGER,balance INTEGER,balance_exact TEXT,balance_base TEXT);CREATE TABLE ledger(id INTEGER PRIMARY KEY,user_id INTEGER,amount INTEGER);INSERT INTO users VALUES(1,'관찰 회원',0,7000000,'7000000','7000000');INSERT INTO ledger VALUES(1,1,10);");
const db={exec:q=>sql.exec(q),prepare:q=>{const v=sql.prepare(q);v.setReadBigInts(true);return v;}};
let clock=Date.parse('2026-11-05T13:10:00+09:00'),calls=0;
const now=()=>clock;
const market={hour:sessionHour(clock),cadenceHours:6,catalogVersion:3,stocks:Object.fromEntries(STOCKS.map(s=>[s.id,{price:String(s.base),changeBp:0,history:[s.base],event:null}]))};
market.stocks.K={price:'57460',changeBp:3000,history:[34000,57460],event:'운영자 수동 변경'};
const savedBefore=JSON.stringify(market.stocks.K);
const olderQuotes=Object.fromEntries(STOCKS.filter(s=>!['K','L'].includes(s.id)).map(s=>[s.id,JSON.stringify(market.stocks[s.id])]));
db.prepare('INSERT INTO game_state(key,value,updated_at) VALUES(?,?,?)').run(MARKET_KEY,JSON.stringify(market),clock);
const marketId='premium-motor-test';
const stock=createJStocks({db,exactWallet,now,randomInt:(min,max)=>{calls++;return min;},marketMode:'kospi'});
function persisted(){return JSON.parse(db.prepare('SELECT value FROM game_state WHERE key=?').get(MARKET_KEY).value);}
const first=stock.status(1);
assert.equal(first.stocks.find(x=>x.id==='L').price,'27000');
assert.equal(first.stocks.find(x=>x.id==='L').changeBp,0);
assert.equal(first.stocks.find(x=>x.id==='L').history.length,1);
assert.equal(first.stocks.find(x=>x.id==='K').price,'57460');
assert.equal(first.stocks.find(x=>x.id==='K').ipoDiscoveryAt,null);
assert.equal(first.changed,true,'Legacy active L IPO must be given one opening quote deadline');
assert.equal(first.nextTickAt,clock+300000,'First IPO quote must become due in five minutes');
assert.equal(first.stocks.find(x=>x.id==='L').ipoDiscoveryAt,clock+300000);
assert.equal(stock.status(1).changed,false,'Do not regenerate opening schedule every request');
clock+=299999;
assert.equal(stock.status(1).changed,false,'Price cannot be edited early');
clock+=1;
const discovered=stock.status(1);
assert.equal(discovered.changed,true);
const newL=discovered.stocks.find(x=>x.id==='L');
assert.notEqual(newL.price,'27000','First IPO session must make a real one-off price move');
assert.notEqual(newL.changeBp,0);
assert.equal(newL.history.length,2);
assert.equal(newL.ipoDiscoveryAt,null);
assert.match(newL.event,/신규상장 첫 가격발견/);
assert.equal(discovered.nextTickAt,Date.parse('2026-11-05T18:00:00+09:00'),'Next tick must be the original six-hour session');
assert.equal(discovered.stocks.find(x=>x.id==='K').price,'57460','Previously admin-adjusted K must not be reset');
assert.equal(JSON.stringify(persisted().stocks.K),savedBefore,'K audit/chart unchanged');
for(const [id,value] of Object.entries(olderQuotes))assert.equal(JSON.stringify(persisted().stocks[id]),value,'Unchanged old stock '+id);
const onePrice=newL.price,oneCalls=calls;
assert.equal(stock.status(1).changed,false,'Another member poll does not mint repeated IPO quotes');
assert.equal(stock.status(1).stocks.find(x=>x.id==='L').price,onePrice);
assert.equal(calls,oneCalls);
clock+=3600000;
assert.equal(stock.status(1).stocks.find(x=>x.id==='L').price,onePrice,'No irregular extra session');
assert.equal(db.prepare('SELECT balance_exact FROM users WHERE id=1').get().balance_exact,'7000000');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ledger').get().n,1n);
const client=fs.readFileSync('public/j-stock.js','utf8'),page=fs.readFileSync('public/index.html','utf8');
assert(client.includes('ipoDiscoveryAt'),'Stock UI must display first opening quote deadline');
assert(client.includes('신규상장 첫 시세 형성'),'Stock UI should label the countdown');
assert(page.includes('20261105-ipo-opening-v1'),'Mobile cache must refresh');
console.log('JSTOCK_IPO_OPENING_OK: L first quote appears after 5m, K +30% preserved, old A-J unchanged, original four sessions and wallets intact');
