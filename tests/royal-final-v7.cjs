'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const {ROYAL_ITEMS}=require('../royal-economy');
const generated=read('public/royal-photo-credits.js');
assert.match(generated,/JunjaRoyalPhotoCredits=Object\.freeze/);
const prefix='Object.freeze(';
const from=generated.indexOf(prefix)+prefix.length;
const info=JSON.parse(generated.slice(from,generated.lastIndexOf(');')));
const photoreal=ROYAL_ITEMS.filter(x=>x.photoFile);
assert.equal(ROYAL_ITEMS.length,40,'legacy inventory must stay intact');
assert.equal(photoreal.length,18,'12 cars + 2 jets + 2 yachts + 2 watches');
const licenses=['CC BY-SA','CC BY','CC0','Public domain','PD'];
for(const item of photoreal){
 const entry=info[item.id];
 assert(entry,'verified image must exist for '+item.id);
 assert(entry.file.startsWith('/art/royal/photos/'),item.id+' local canonical path');
 assert(entry.source.startsWith('https://commons.wikimedia.org/wiki/File:'),'source link for '+item.id);
 assert(entry.author.length>=2,'photographer name for '+item.id);
 assert(licenses.some(x=>entry.license.includes(x)),item.id+' licensed for use');
 assert(entry.licenseUrl.startsWith('https://'),'license URL '+item.id);
 assert(entry.transformation.includes('Resized'),'disclosure of crop/grade '+item.id);
 const local=path.join(root,'public',entry.file.slice(1));
 assert(fs.existsSync(local),'local real photo is missing: '+local);
 const buf=fs.readFileSync(local);
 assert(buf.subarray(0,4).toString('ascii')==='RIFF'&&buf.subarray(8,12).toString('ascii')==='WEBP','valid WebP photo '+item.id);
 assert(buf.length>18000&&buf.length<450000,'optimized offline photo size '+item.id+' '+buf.length);
}
const server=read('server.js');
assert(server.includes("img-src 'self' data: https://commons.wikimedia.org https://upload.wikimedia.org"),'CSP must permit trusted remote photo fallback but no arbitrary origins');
const index=read('public/index.html');
const media=read('public/royal-photo.js');
assert(index.indexOf('royal-photo-credits.js')<index.indexOf('/royal-photo.js'),'load verified photo credits before common photo resolver');
assert(media.includes('verified(item)?.file||external(item)'),'prefer self-hosted photos to remote Wikimedia');
assert(media.includes('creditName=item=>verified(item)?.author'),'show verified photographer not guessed text');
assert(media.includes('licenseName=item=>verified(item)?.license'),'show actual license metadata');
const museum=read('public/royal-gallery.js');
const css=read('public/royal-gallery.css');
assert(museum.includes('jrg-cinematic-entrance'),'owner cinema view renders');
assert(museum.includes('photoMasterpiece=items.find'),'cinema shows actual purchased work only');
assert(museum.includes('totalItems||40'),'accurate 40 piece collection count');
assert(css.includes('jrg-cinematic-entrance>img'),'photographic gallery hero');
assert(css.includes('.main-app:has(#view-shop.active)>.topbar'),'compact mobile HUD on luxury screens only');
console.log('ROYAL_PHOTOREAL_FINAL_OK: verified 18 locally hosted/licensed real photos, safe CSP, full-image garage, 40-piece inventory, responsive HUD');
