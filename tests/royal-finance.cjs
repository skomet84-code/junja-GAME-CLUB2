'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const exactWallet=require('../exact-wallet');
const {createJBank}=require('../j-bank-core');
const {createRoyalEconomy,ROYAL_ITEMS}=require('../royal-economy');
const native=new DatabaseSync(':memory:');
const norm=v=>{if(typeof v==='bigint')return v<=BigInt(Number.MAX_SAFE_INTEGER)&&v>=-BigInt(Number.MAX_SAFE_INTEGER)?Number(v):String(v);if(v&&typeof v==='object')for(const k of Object.keys(v))v[k]=norm(v[k]);return v;};
const db={exec:q=>native.exec(q),prepare:q=>{const s=native.prepare(q);s.setReadBigInts(true);return {run(...a){return s.run(...a)},get(...a){return norm(s.get(...a))},all(...a){return s.all(...a).map(norm)}}}};
db.exec('CREATE TABLE users(id INTEGER PRIMARY KEY,nickname TEXT,balance INTEGER,balance_exact TEXT,balance_base TEXT,rank_level INTEGER DEFAULT 0,is_disabled INTEGER DEFAULT 0);CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT,updated_at INTEGER);CREATE TABLE user_inventory(user_id INTEGER NOT NULL,item_id TEXT NOT NULL,purchase_price INTEGER,purchased_at INTEGER,PRIMARY KEY(user_id,item_id));CREATE TABLE user_loadout(user_id INTEGER PRIMARY KEY,character TEXT,costume TEXT,frame TEXT,title TEXT,pet TEXT);CREATE TABLE ledger(id INTEGER PRIMARY KEY AUTOINCREMENT,user_id INTEGER,amount INTEGER,balance_after INTEGER,amount_exact TEXT,balance_after_exact TEXT,type TEXT,memo TEXT,created_at INTEGER);CREATE TABLE room_escrow(room_id TEXT,user_id INTEGER,amount INTEGER,game TEXT,created_at INTEGER);');
const G=10n**16n,at=Date.parse('2026-11-03T13:00:00+09:00'),now=()=>at,kstDate=()=>new Date(at+9*3600000).toISOString().slice(0,10);
function user(id,rank,balance){
 const mirror=exactWallet.mirror(balance);
 db.prepare('INSERT INTO users(id,nickname,rank_level,balance,balance_exact,balance_base) VALUES(?,?,?,?,?,?)').run(id,'컬렉터'+id,rank,mirror,String(balance),String(mirror));
}
user(1,12,G/2n);user(2,0,0n);user(3,12,0n);
const ranks=Array.from({length:14},(_,i)=>({level:i,name:'신분'+i,cost:0}));
const bank=createJBank({db,exactWallet,levels:ranks,now,kstDate});
const royal=createRoyalEconomy({db,exactWallet,now,getAssets:()=>({})});
royal.setBank(bank);
const cheap=ROYAL_ITEMS.find(x=>x.id==='jewel_royalboutique_platinum_drop');
const costly=ROYAL_ITEMS.find(x=>BigInt(x.price)>30n*G);
const wallet=id=>exactWallet.read(db.prepare('SELECT balance,balance_exact,balance_base FROM users WHERE id=?').get(id));
assert(cheap&&costly);
assert.equal(royal.catalog(1).financing.canBorrow,true);
assert.equal(bank.purchaseQuote(1,cheap.price).eligible,true);
assert.equal(bank.purchaseQuote(1,cheap.price).loanAmount,String(G/2n));
assert.throws(()=>royal.buy(1,cheap.id),/게임머니가 부족/);
assert.equal(bank.status(1).outstanding,'0','no involuntary loan');
const receipt=royal.buy(1,cheap.id,{loanPurchase:true});
assert.equal(receipt.loanAmount,String(G/2n));
assert.equal(receipt.balance,'0');
assert.equal(wallet(1),0n,'loan funds spent on purchased artifact');
assert.equal(bank.status(1).outstanding,String(G/2n),'only required shortage is financed');
assert.equal(royal.catalog(1).items.find(x=>x.id===cheap.id).owned,true);
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM ledger WHERE user_id=1 AND type='jbank_purchase_loan'").get().n,1);
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM ledger WHERE user_id=1 AND type='royal_boutique_purchase'").get().n,1);
assert.throws(()=>royal.buy(1,cheap.id,{loanPurchase:true}),/이미 영구 소장/);
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM ledger WHERE user_id=1 AND type='jbank_purchase_loan'").get().n,1,'repeated purchase cannot borrow twice');
assert.equal(bank.status(1).canBorrow,false,'original J-BANK no-overlapping-loan rule preserved');
assert.equal(bank.purchaseQuote(1,cheap.price).eligible,false,'cannot borrow again while indebted');
assert.throws(()=>royal.buy(2,cheap.id,{loanPurchase:true}),/대출 한도|은행 대출/);
assert.equal(bank.status(2).outstanding,'0');
assert.throws(()=>royal.buy(3,costly.id,{loanPurchase:true}),/대출 한도|은행 대출/);
assert.equal(bank.status(3).outstanding,'0');
assert.equal(wallet(3),0n);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM user_inventory WHERE user_id=3').get().n,0);
console.log('ROYAL_LOAN_FINANCE_OK: explicit opt-in, shortfall only, atomic loan+ownership, no duplicate or over-limit debt');
