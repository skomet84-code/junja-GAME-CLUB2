'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createMotorDesignStudio}=require('../premium-motor-design');
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT,updated_at INTEGER);CREATE TABLE users(id INTEGER PRIMARY KEY,nickname TEXT,is_disabled INTEGER NOT NULL DEFAULT 0,balance INTEGER);CREATE TABLE ledger(id INTEGER PRIMARY KEY,user_id INTEGER,amount INTEGER);INSERT INTO users VALUES(1,'소버린 디자이너',0,10000),(2,'방문 회원',0,20000),(3,'이용중지',1,30000);INSERT INTO ledger VALUES(1,1,-50);");
let clock=Date.UTC(2026,10,5);
let studio=createMotorDesignStudio({db,now:()=>clock});
const a={paint:'onyx',doorsOpen:true,lightsOn:true,rotation:-.61,pitch:.24,zoom:8.5};
const b={paint:'champagne',doorsOpen:false,lightsOn:false,rotation:3.14,pitch:.10,zoom:9.4};
assert.equal(studio.read(1).version,0);
assert.equal(studio.read(1).owned,false);
assert.equal(studio.read(1).purchased,false);
assert.equal(studio.read(1).published,false);
assert.equal(studio.read(1).shareToken,null);
assert.throws(()=>studio.read(3),/이용할 수 없는/);
assert.throws(()=>studio.shared({token:'bad'}),/공유 링크/);
assert.throws(()=>studio.save({userId:1,design:a,published:false,expectedVersion:0,requestId:'short'}),/요청번호/);
assert.throws(()=>studio.save({userId:1,design:{...a,paint:'ferrari'},published:false,expectedVersion:0,requestId:'motor_save_00000001'}),/도장/);
assert.throws(()=>studio.save({userId:1,design:{...a,zoom:NaN},published:false,expectedVersion:0,requestId:'motor_save_00000001'}),/카메라/);
assert.throws(()=>studio.save({userId:1,design:{...a,owned:true},published:false,expectedVersion:0,requestId:'motor_save_00000001'}),/알 수 없는/);
const saved=studio.save({userId:1,design:a,published:false,expectedVersion:0,requestId:'motor_save_00000001'});
assert.equal(saved.version,1);
assert.equal(saved.published,false);
assert.equal(saved.owned,false);
assert.equal(saved.shareToken,null);
assert.deepEqual(studio.read(1).design,a);
assert.equal(studio.save({userId:1,design:a,published:false,expectedVersion:0,requestId:'motor_save_00000001'}).duplicate,true);
assert.throws(()=>studio.save({userId:1,design:b,published:false,expectedVersion:0,requestId:'motor_save_00000001'}),/다른 내용/);
assert.throws(()=>studio.save({userId:1,design:b,published:false,expectedVersion:0,requestId:'motor_save_00000002'}),/다른 창/);
const public1=studio.save({userId:1,design:a,published:true,expectedVersion:1,requestId:'motor_publish_000001'});
assert.equal(public1.version,2);
assert.match(public1.shareToken,/^[\w-]{24}$/);
assert.equal(studio.shared({token:public1.shareToken}).published,true);
assert.equal(studio.shared({token:public1.shareToken}).shareToken,null,'Visitor cannot discover owner token in response');
assert.equal(studio.shared({token:public1.shareToken}).designerNickname,'소버린 디자이너');
assert.equal(studio.shared({token:public1.shareToken}).owned,false);
assert.equal(studio.read(2).version,0,'Other account has no private owner data');
const modified=studio.save({userId:1,design:b,published:true,expectedVersion:2,requestId:'motor_publish_000002'});
assert.equal(modified.shareToken,public1.shareToken,'Ordinary change retains secret');
assert.equal(studio.shared({token:public1.shareToken}).design.paint,'champagne');
const rotated=studio.save({userId:1,design:b,published:true,rotateShare:true,expectedVersion:3,requestId:'motor_publish_000003'});
assert.notEqual(rotated.shareToken,public1.shareToken);
assert.throws(()=>studio.shared({token:public1.shareToken}),/찾을 수/);
assert.equal(studio.shared({token:rotated.shareToken}).published,true);
const hidden=studio.save({userId:1,design:a,published:false,expectedVersion:4,requestId:'motor_unpublish_00001'});
assert.equal(hidden.shareToken,null);
assert.throws(()=>studio.shared({token:rotated.shareToken}),/찾을 수/);
const noLeak=db.prepare("SELECT COUNT(*) AS n FROM game_state WHERE key LIKE 'premium:motor-share:v1:%'").get().n;
assert.equal(noLeak,0,'Unpublish removes all active public indices');
assert.equal(db.prepare('SELECT SUM(balance) AS money FROM users').get().money,60000);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ledger').get().n,1);
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM game_state WHERE key LIKE 'premium_store%' OR key LIKE 'jbank:%'").get().n,0);
clock+=86400000;studio=createMotorDesignStudio({db,now:()=>clock});
assert.equal(studio.read(1).version,5,'Design must survive restart');
assert.equal(studio.read(1).published,false);
db.prepare('UPDATE users SET is_disabled=1 WHERE id=1').run();
assert.throws(()=>studio.read(1),/이용할 수 없는/);
db.close();
console.log('MOTOR_DESIGN_V1_OK: private versioned drafts, owner-only read, opt-in visitor share, link rotation/revocation, restart, no wallet or entitlement changes');
