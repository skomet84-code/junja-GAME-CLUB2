'use strict';
const assert=require('node:assert/strict'),E=require('../public/blackroom/engine.js');
const s=E.initial();
assert.equal(E.travel(s,'room').ok,false);
assert.equal(E.collect(s,'footage').ok,false);
assert.equal(E.puzzle(s,'door','4444').ok,false);
assert.equal(E.collect(s,'guest').ok,true);
assert.equal(E.puzzle(s,'door','2317').ok,true);
['clock','latch','invitation','lock','thread','footprint','sync','ledger'].forEach(id=>assert.equal(E.collect(s,id).ok,true,id));
assert.equal(E.collect(s,'footage').ok,false);
assert.equal(E.puzzle(s,'archive','0713').ok,true);
assert.equal(E.collect(s,'footage').ok,true);
assert.equal(E.connect(s,'guest','clock').ok,false,'unrelated evidence must not form theory');
[['clock','sync'],['guest','lock'],['invitation','footage']].forEach(([a,b])=>assert.equal(E.connect(s,a,b).ok,true));
assert.equal(E.ready(s),true);
assert.equal(E.interrogate(s,'kang').reveal,true);
assert.equal(E.verdict(s,{culprit:'lee',time:'offset',method:'maintenance'}).ok,false);
assert.equal(E.verdict(s,{culprit:'kang',time:'offset',method:'maintenance'}).ok,true);
assert.equal(E.hydrate(JSON.parse(JSON.stringify(s))).solved,true);
assert.equal(E.hydrate({v:1,scene:'security',door:false,archive:false,clues:['footage']}).clues.length,0);
console.log('BLACKROOM_EP01_OK — gating, deduction, interrogations, two endings and save invariants');
