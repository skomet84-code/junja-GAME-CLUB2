'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.join(__dirname,'..'),read=x=>fs.readFileSync(path.join(root,x),'utf8');
const page=read('public/premium-sovereign-atelier.html');
const script=read('public/premium-sovereign-atelier.js');
const css=read('public/premium-sovereign-atelier.css');
const old=read('public/premium-sovereign-lab.html');
const license=read('docs/SOVEREIGN_ATELIER_CC0_ASSET.md');
const deps=JSON.parse(read('package.json'));
assert.equal(deps.dependencies.three,'0.180.0','Three engine must be version-pinned');
assert(page.includes('three/addons/')&&page.includes('type="importmap"'),'Locally hosted modern glTF render modules required');
assert(!/<script[^>]*src=["']https?:\/\//i.test(page),'Never depend on third party JS at page runtime');
assert(!/TossPayments|confirmPayment|\/api\/premium\/buy|\/api\/premium\/checkout|localStorage|sessionStorage/.test(script),'No money or fake entitlement');
assert(page.includes('미소유')&&page.includes('판매 불가'));
assert(page.includes('Spectral GT RS')&&page.includes('CC0'));
assert(old.includes('motorDesignPanel'),'Existing member draft flow must be intact');
for(const mode of ['hero','front','side','rear','detail'])assert(page.includes('data-at-view="'+mode+'"'));
for(const id of ['atelierCanvas','atelierLoading','atelierFallback','atelierPaint','atelierDoor','atelierHood','atelierLight','atelierReset'])assert(page.includes('id="'+id+'"'));
assert(script.includes("new GLTFLoader().loadAsync('/art/royal/models/spectral-gt-rs-cc0.glb'"),'Must load real local GLB');
assert(script.includes('new THREE.WebGLRenderer')&&script.includes('RoomEnvironment'),'Real WebGL physical lighting required');
assert(script.includes('new THREE.AnimationMixer')&&script.includes('paintMaterials.push'),'Actual asset animations and body paint required');
assert(css.includes('@media(max-width:690px)'),'Narrow phone responsiveness required');
assert(license.includes('34499c501908818a2b08e589a7aecf963343cee7'));
const glbPath=path.join(root,'public/art/royal/models/spectral-gt-rs-cc0.glb'),buf=fs.readFileSync(glbPath);
assert.equal(buf.toString('ascii',0,4),'glTF');
assert.equal(buf.readUInt32LE(4),2);
assert.equal(buf.readUInt32LE(8),buf.length);
assert(buf.length>1_000_000);
const gitSha=crypto.createHash('sha1').update('blob '+buf.length+'\0').update(buf).digest('hex');
assert.equal(gitSha,'f5b814848453a6c75a48f5047fdadaa7bdc78969','Asset must equal pinned CC0 source');
assert.equal(buf.readUInt32LE(16),0x4e4f534a);
const json=JSON.parse(buf.subarray(20,20+buf.readUInt32LE(12)).toString('utf8'));
assert(Array.isArray(json.meshes)&&json.meshes.length>30,'High detail GLB meshes required');
assert(Array.isArray(json.materials)&&json.materials.length>10,'PBR materials required');
assert(Array.isArray(json.animations)&&json.animations.length>=4,'Door and hood animation clips required');
assert(json.materials.some(x=>String(x.name).includes('Spectral Blue')),'Must have a real paint material');
assert(fs.statSync(path.join(root,'public/vendor/three/build/three.module.js')).size>10000);
for(const f of ['build/three.core.js','examples/jsm/loaders/GLTFLoader.js','examples/jsm/controls/OrbitControls.js','examples/jsm/utils/BufferGeometryUtils.js','examples/jsm/environments/RoomEnvironment.js','LICENSE'])
 assert(fs.statSync(path.join(root,'public/vendor/three',f)).size>100);
console.log('SOVEREIGN_ATELIER_OK: verified CC0 source sha='+gitSha+', '+json.meshes.length+' glTF meshes, '+json.materials.length+' materials, '+json.animations.length+' animations, own-hosted Three.js MIT, payments disabled');
