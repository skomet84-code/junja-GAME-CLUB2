'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {DatabaseSync}=require('node:sqlite');
const {report}=require('../jpl-admin-report');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE users(id INTEGER PRIMARY KEY,username TEXT,nickname TEXT);CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT,updated_at INTEGER)');
const put=(k,v)=>db.prepare('INSERT INTO game_state(key,value,updated_at) VALUES(?,?,?)').run(k,JSON.stringify(v),1);
db.prepare('INSERT INTO users(id,username,nickname) VALUES(?,?,?)').run(1,'junja','준자');
db.prepare('INSERT INTO users(id,username,nickname) VALUES(?,?,?)').run(2,'happy','햅피');
put('jpl:v1:current',{id:'S2'});
const leg=(matchId,pick,market='NORMAL')=>({matchId,home:'junja',away:'happy',pick,market,line:0,kickoff:100000,odds100:190});
put('jpl:v1:ticket:S1:1:abc',{id:'abc',seasonId:'S1',userId:1,stake:'1000000000000',potential:'1900000000000',paid:'1900000000000',tax:'0',status:'WIN',placedAt:1000,receiptNumber:'JPL-S1-1-ABC',totalOdds:'1.90',legs:[leg('m1','H')]});
put('jpl:v1:ticket:S2:1:def',{id:'def',seasonId:'S2',userId:1,stake:'2000000000000',potential:'7000000000000',expectedNet:'7000000000000',paid:'0',status:'OPEN',placedAt:2000,totalOdds:'3.50',legs:[leg('m2','D'),leg('m3','A','HDP')]});
put('jpl:v1:ticket:S2:2:ghi',{id:'ghi',seasonId:'S2',userId:2,stake:'3000000000000',potential:'5000000000000',paid:'0',status:'LOSE',placedAt:3000,totalOdds:'1.67',legs:[leg('m2','H')]});
const current=report(db);
assert.equal(current.currentSeason,'S2');
assert.equal(current.summary.tickets,2);
assert.equal(current.summary.staked,'5000000000000','multi-leg slips do not multiply unique stake');
assert.equal(current.summary.open,1);
assert.equal(current.summary.lose,1);
assert.equal(current.summary.expected,'7000000000000');
assert.equal(current.summary.bettors,2);
assert.equal(current.matches.find(m=>m.matchId==='m2').picks.H.count,1);
assert.equal(current.matches.find(m=>m.matchId==='m2').picks.D.stake,'2000000000000');
assert.equal(current.matches.find(m=>m.matchId==='m3').market,'HDP');
assert.equal(current.tickets[0].nickname,'햅피','tickets sort newest-first');
assert.equal(current.clubNames.junja,'준자');
const all=report(db,{season:'all'});
assert.equal(all.summary.tickets,3);
assert.equal(all.summary.staked,'6000000000000');
assert.equal(all.summary.paid,'1900000000000');
assert.deepEqual(all.seasons,['S2','S1']);
assert.equal(report(db,{season:'all',user:'준자'}).summary.tickets,2);
assert.equal(report(db,{season:'all',user:'HAPPY'}).summary.tickets,1);
assert.equal(report(db,{status:'WIN'}).summary.tickets,0);
assert.equal(report(db,{season:'all',status:'WIN'}).summary.tickets,1);
assert.throws(()=>report(db,{season:'../etc'}),/시즌/);
assert.throws(()=>report(db,{status:'bad'}),/상태/);
const server=fs.readFileSync('server.js','utf8');
const start=server.indexOf("if(url.pathname==='/api/admin/jpl-bets'");
assert.ok(start>=0,'admin betting API must exist');
assert.ok(server.slice(start,start+200).includes('requireAdmin(req,res)'),'server gate must check verified administrator');
const html=fs.readFileSync('public/football/index.html','utf8');
assert.ok(html.includes('id="adminPanel" hidden'),'admin dashboard is hidden before authenticated verification');
assert.ok(html.includes('id="adminNav" hidden'),'operator nav is hidden from regular members');
const front=fs.readFileSync('public/football/admin.js','utf8');
assert.ok(front.includes("Number(d?.user?.is_admin)!==1"),'frontend checks user role before revealing tab');
assert.ok(front.includes("'/api/admin/jpl-bets?'"),'admin panel queries protected endpoint');
console.log('JPL_ADMIN_OK: privacy, history, parlay exposure, settlement, filtering and admin controls');
