'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createMarketControl,percentBp}=require('../market-operator');
const {STOCKS:stocks,MARKET_KEY:stockKey,createJStocks,sessionHour:stockSessionHour}=require('../j-stock-core');
const {STOCKS:coins,MARKET_KEY:coinKey,createJCoins}=require('../j-coin-core');
const exactWallet=require('../exact-wallet');
const db=new DatabaseSync(':memory:');
db.exec("CREATE TABLE game_state(key TEXT PRIMARY KEY,value TEXT NOT NULL,updated_at INTEGER NOT NULL);CREATE TABLE users(id INTEGER PRIMARY KEY,nickname TEXT,is_disabled INTEGER DEFAULT 0,balance INTEGER DEFAULT 1000000,balance_exact TEXT,balance_base TEXT);CREATE TABLE ledger(id INTEGER PRIMARY KEY,user_id INTEGER,type TEXT,amount INTEGER,balance_after INTEGER);INSERT INTO users(id,nickname) VALUES(1,'대표'),(2,'회원');INSERT INTO ledger VALUES(1,2,'old',100,100);");
let clock=Date.UTC(2026,10,5,3,0);
const now=()=>clock;
const write=(k,v)=>db.prepare('INSERT INTO game_state(key,value,updated_at) VALUES(?,?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value,updated_at=excluded.updated_at').run(k,JSON.stringify(v),clock);
const read=k=>JSON.parse(db.prepare('SELECT value FROM game_state WHERE key=?').get(k).value);
write(stockKey,{hour:stockSessionHour(clock),cadenceHours:6,catalogVersion:2,stocks:Object.fromEntries(stocks.map(x=>[x.id,{price:String(x.base),changeBp:0,history:[x.base],event:null}]))});
write(coinKey,{hour:Math.floor(clock/900000)*0.25,cadenceHours:0.25,catalogVersion:1,stocks:Object.fromEntries(coins.map(x=>[x.id,{price:String(x.base),changeBp:0,history:[x.base],event:null}]))});
const control=createMarketControl({db,now});
assert.equal(control.list().markets.stock.length,10);
assert.equal(control.list().markets.coin.length,8);
assert.equal(control.volatilityFor('stock','A'),100);
assert.equal(percentBp('-3.25'),-325);
assert.equal(percentBp('+132.00'),13200);
assert.throws(()=>percentBp('1e3'),/소수점/);
const input={actorId:1,type:'stock',symbol:'A',mode:'price',deltaPercent:'10.00',expectedPrice:'100000',requestId:'market_stock_00000001'};
const result=control.apply(input);
assert.equal(result.previousPrice,'100000');
assert.equal(result.price,'110000');
assert.equal(result.changeBp,1000);
assert.equal(read(stockKey).stocks.A.price,'110000');
assert.equal(read(stockKey).stocks.B.price,'75000');
assert.equal(control.apply(input).duplicate,true);
assert.equal(read(stockKey).stocks.A.price,'110000');
assert.equal(control.list().history.length,1);
assert.throws(()=>control.apply({...input,requestId:'market_stock_00000002'}),/최신 가격/);
assert.throws(()=>control.apply({...input,requestId:'market_stock_00000003',expectedPrice:'110000',deltaPercent:'31'}),/±30/);
assert.throws(()=>control.apply({...input,requestId:'market_stock_00000004',symbol:'X'}),/유효하지/);
assert.throws(()=>control.apply({...input,requestId:'market_stock_00000005',expectedPrice:'110000',deltaPercent:'0'}),/0%/);
assert.throws(()=>control.apply({...input,requestId:'market_stock_00000006',expectedPrice:'110000',deltaPercent:'-100'}),/±30/);
const volInput={actorId:1,type:'stock',symbol:'A',mode:'volatility',volatilityPct:200,requestId:'market_vol_000000001'};
const v=control.apply(volInput);
assert.equal(v.volatilityPct,200);
assert.equal(control.volatilityFor('stock','A'),200);
assert.equal(control.volatilityFor('stock','B'),100);
assert.equal(control.apply(volInput).duplicate,true);
assert.throws(()=>control.apply({...volInput,requestId:'market_vol_000000002',volatilityPct:999}),/50%/);
const coin=control.apply({actorId:1,type:'coin',symbol:'JJC',mode:'price',deltaPercent:'132.00',expectedPrice:'1000000',requestId:'market_coin_00000001'});
assert.equal(coin.price,'2320000');
assert.equal(read(coinKey).stocks.JJC.price,'2320000');
const moon=control.apply({actorId:1,type:'coin',symbol:'MOON',mode:'price',deltaPercent:'-57.00',expectedPrice:'10000',requestId:'market_coin_00000002'});
assert.equal(moon.price,'4300');
assert.equal(control.list().history.length,4);
const beforeUsers=db.prepare('SELECT balance FROM users WHERE id=2').get().balance;
const beforeLedger=db.prepare('SELECT COUNT(*) AS n FROM ledger').get().n;
assert.equal(beforeUsers,1000000);
assert.equal(beforeLedger,1);
write('jcoin:temporary:moon-jjc-20261103-v1',{startedAt:clock,endsAt:clock+7200000,complete:false});
assert.throws(()=>control.apply({actorId:1,type:'coin',symbol:'MOON',mode:'price',deltaPercent:'+10',expectedPrice:'4300',requestId:'market_coin_00000003'}),/2시간/);
const dog=control.apply({actorId:1,type:'coin',symbol:'DOGJ',mode:'volatility',volatilityPct:50,requestId:'market_dog_000000001'});
assert.equal(dog.volatilityPct,50);
assert.equal(control.volatilityFor('coin','DOGJ'),50);
assert.equal(db.prepare('SELECT balance FROM users WHERE id=2').get().balance,beforeUsers);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ledger').get().n,beforeLedger);
// New instance after "restart" reads the same persisted market settings and audit history.
const second=createMarketControl({db,now});
assert.equal(second.list().markets.coin.find(x=>x.id==='JJC').price,'2320000');
assert.equal(second.volatilityFor('stock','A'),200);
assert.equal(second.list().history.length,5);
assert.throws(()=>second.apply({...volInput,volatilityPct:50}),/이미 다른 시장 변경/);
// Verify presets affect future real market-tick volatility, not only stored settings.
const randomInt=(a,b)=>b-1;
const stock=createJStocks({db,exactWallet,now,randomInt,getVolatilityPct:id=>second.volatilityFor('stock',id)});
clock+=6*3600000;
const fresh=stock.status(1);
assert(fresh.stocks.find(x=>x.id==='A').price!=='110000');
const sA=fresh.stocks.find(x=>x.id==='A'),sB=fresh.stocks.find(x=>x.id==='B');
assert(sA.changeBp>sB.changeBp,'200% preset must increase the relative future move on A');
assert.equal(second.list().markets.stock.find(x=>x.id==='A').price,sA.price);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM ledger').get().n,1);
// Mode default retains exact legacy market price behavior for other stocks.
db.close();
console.log('OWNER_MARKET_CORE_OK: 10 stocks, 8 coins, +132/-57, bounded changes, optimistic lock, idempotency, audit, persistence, real future volatility, zero wallet writes');
