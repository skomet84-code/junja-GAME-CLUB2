'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const server=fs.readFileSync(path.join(__dirname,'..','server.js'),'utf8');
const rankJs=fs.readFileSync(path.join(__dirname,'..','public','rank-system.js'),'utf8');
const rankCss=fs.readFileSync(path.join(__dirname,'..','public','rank-system.css'),'utf8');
const exact=require('../exact-wallet');
const start=server.indexOf('const SOCIAL_RANKS = [');
const end=server.indexOf('function socialRankPerksForUser(',start);
assert.ok(start>=0&&end>start,'rank definitions found');
const context={};
vm.runInNewContext(server.slice(start,end)+';globalThis.ranks=SOCIAL_RANKS;globalThis.perks=socialRankPerks;',context);
const ranks=context.ranks,perks=context.perks;
assert.equal(ranks.length,14);
assert.equal(ranks[12].name,'GOD JUNJA');
assert.equal(ranks[13].name,'THE ABSOLUTE');
assert.equal(ranks[13].className,'absolute');
assert.equal(BigInt(ranks[13].cost),1000000000000000000n,'100경 exact integer');
assert.equal(perks(12).dailySalary,10000000000,'preserve GOD salary');
assert.equal(perks(12).freeSlots,200,'preserve GOD free slots');
assert.equal(perks(12).dailyDraws,7,'preserve GOD daily draw');
assert.equal(perks(13).dailySalary,100000000000);
assert.equal(perks(13).dailyDraws,10);
assert.equal(perks(13).freeSlots,500);
assert.equal(perks(13).freeBigWheel,500);
assert.equal(perks(13).transferFeePct,0);
assert.ok(perks(13).shopTier>perks(12).shopTier);
const original=1000000000000000000n+1234567890123456789n;
const remaining=original-BigInt(ranks[13].cost);
const shadow=exact.mirror(remaining);
assert.equal(exact.read({balance:shadow,balance_exact:String(remaining),balance_base:String(shadow)}),remaining,'no truncation after purchase');
assert.ok(rankJs.includes('THE ONE ABOVE ALL'),'new tier hero');
assert.ok(rankJs.includes('BEYOND OMNIPOTENCE'),'new tier power panel');
assert.ok(rankCss.includes('.rank-hero.rank-absolute'),'new rank visible');
assert.ok(server.includes('SELECT balance,balance_exact,balance_base,last_rank_salary'),'salary uses exact wallet');
assert.ok(server.includes('SELECT balance,balance_exact,balance_base,last_daily'),'attendance uses exact wallet');
console.log('ABSOLUTE_RANK_TESTS_OK');
